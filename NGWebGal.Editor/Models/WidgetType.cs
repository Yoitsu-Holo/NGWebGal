namespace NGWebGal.Editor.Models;

/// <summary>
/// Defines the types of widgets available in the editor.
/// </summary>
public enum WidgetType
{
    /// <summary>
    /// Image display widget.
    /// </summary>
    ImageBox,

    /// <summary>
    /// Text display widget.
    /// </summary>
    TextBox,

    /// <summary>
    /// Colored rectangle widget.
    /// </summary>
    ColorBox,

    /// <summary>
    /// Progress bar widget.
    /// </summary>
    ProgressBar,

    /// <summary>
    /// Clickable button widget.
    /// </summary>
    Button,

    /// <summary>
    /// Toggle switch widget.
    /// </summary>
    Toggle,

    /// <summary>
    /// Checkbox widget.
    /// </summary>
    Checkbox,

    /// <summary>
    /// Horizontal slider widget.
    /// </summary>
    SliderHorizontal,

    /// <summary>
    /// Vertical slider widget.
    /// </summary>
    SliderVertical,

    /// <summary>
    /// Text input field widget.
    /// </summary>
    InputField
}
